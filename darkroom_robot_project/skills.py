import time

from driver_sdk import JOINT_IDS, STS3215Driver

PORT = "/dev/ttyACM0"
SPEED = 500
WAIT = 0.0          # 도착 후 추가로 더 쉬는 시간(초). 0이면 곧바로 다음 스텝

# 스텝 완료 판정 — 둘 중 먼저 오는 쪽으로 다음 스텝 진행
#   (1) 도착   목표와의 차이가 ARRIVE_TICK 이내
#   (2) 멈춤   더 이상 안 움직임 — 중력·마찰로 목표 앞에서 서거나 그리퍼가 샘플을 물었을 때
# 실제 도착을 보고 판단하므로 속도를 올리면 대기도 알아서 짧아진다
ARRIVE_TICK = 20    # 목표와 이만큼 이내면 도착 (1틱 ≈ 0.09°, 20틱 ≈ 1.8°)
STILL_TICK = 3      # 이 이하로만 움직이면 멈춘 것으로 봄
STILL_HOLD = 0.12   # 멈춘 상태가 이만큼 이어지면 완료
START_GRACE = 0.25  # 명령 직후 이 시간은 멈춤 판정 보류 (출발 전 오판 방지)
ARRIVE_MAX = 8.0    # 안전 상한(초). 넘으면 경고 남기고 다음 스텝
POLL = 0.01         # 위치 확인 주기(초). 6축 1회 읽기가 2ms라 여유 있음

# J6만 바뀌는 스텝(그립·개방)은 위치를 재지 않고 이만큼 고정으로 기다린다.
# 샘플을 물면 목표까지 못 가서 도착 판정이 애매해지는 구간이라 시간으로 끊는 편이 확실하다.
GRIP_WAIT = 0.5

# 속도 배율 — spd()에 적어둔 값을 건드리지 않고 전체 속도만 올린다.
# 한 스텝 안의 관절 비율(어느 관절이 먼저 도착하는지)이 동작 모양을 만들기 때문에
# 배율은 스텝 단위로 똑같이 곱한다. 다만 한 관절이라도 SPEED_LIMIT을 넘으면
# 그 관절만 잘려서 비율이 틀어지므로, 그럴 땐 스텝 전체 배율을 같이 낮춘다.
#   예) J2=300 · J5=1500 스텝에 500% → J5가 7500이라 상한 초과
#       → 스텝 전체를 273%로 낮춰 300:1500 비율을 그대로 유지
SPEED_SCALE = 1.0     # 1.0 = 100%
SCALE_MIN = 1.0       # 100% — 기준보다 느리게는 안 감
SCALE_MAX = 2.5       # 250%까지만 허용 (UI 게이지바·직접입력·set_speed_scale 모두 여기서 잘림)
                      # 현재 최고 속도값이 1500(2차 12번·3차 7번 J5)이라
                      # 1500 × 2.73 = 4095(상한)에서 배율이 막힌다. 즉 273%가 물리적 한계.
                      # 그 아래인 250%로 두면 전 스텝이 요청한 배율 그대로 따라온다.
                      # 더 올리고 싶으면 spd()의 1500을 낮추는 게 먼저다.
SPEED_LIMIT = 4095    # 서보 속도 레지스터 상한

_driver = STS3215Driver(port=PORT)


def set_wait(seconds):
    global WAIT
    WAIT = float(seconds)


def set_grip_wait(seconds):
    """J6만 바뀌는 스텝의 고정 대기(초)를 한 번에 바꾼다 — 4개 스텝에 모두 적용."""
    global GRIP_WAIT
    GRIP_WAIT = float(seconds)


def set_speed_scale(percent):
    """속도 배율(%)을 바꾼다. SCALE_MIN~SCALE_MAX(100~250%)로 잘라서 적용하고 적용값을 돌려준다."""
    global SPEED_SCALE
    SPEED_SCALE = max(SCALE_MIN, min(SCALE_MAX, float(percent) / 100.0))
    return SPEED_SCALE * 100


def _scaled(speeds):
    """스텝 속도에 배율을 먹인다. (관절별 속도, 실제 적용 배율) 반환.

    전 관절에 같은 값을 곱해야 비율이 유지된다.
    상한을 넘는 관절이 생기면 그 관절만 잘리며 비율이 깨지므로,
    가장 빠른 관절이 상한에 딱 맞도록 스텝 전체 배율을 낮춘다.
    """
    raw = {sid: (SPEED if speeds.get(sid) is None else speeds[sid]) for sid in JOINT_IDS}
    top = max(raw.values())
    scale = min(SPEED_SCALE, SPEED_LIMIT / top) if top > 0 else SPEED_SCALE
    return {sid: max(1, round(v * scale)) for sid, v in raw.items()}, scale


def spd(j1=None, j2=None, j3=None, j4=None, j5=None, j6=None):
    """속도 줄 — 바로 아래 pos() 줄부터 적용. 생략한 관절은 기본 SPEED."""
    return ("SPD", {1: j1, 2: j2, 3: j3, 4: j4, 5: j5, 6: j6})


def pos(pose, name):
    """위치 줄 — 바로 위 spd() 속도로 이동."""
    return ("POS", pose, name)


def _grip_only(pose, prev):
    """이전 자세와 J6만 다른 스텝인지 — 팔은 그대로 두고 그리퍼만 여닫는 구간."""
    return (
        prev is not None
        and pose[6] != prev[6]
        and all(pose[s] == prev[s] for s in (1, 2, 3, 4, 5))
    )


def _wait_arrival(goal):
    """스텝이 끝날 때까지 대기. (걸린 시간, 사유) 반환.

    목표에 들어오면 '도착', 목표 앞에서 더 안 움직이면 '멈춤'으로 끝낸다.
    중력·마찰로 수십 틱 남기고 서는 경우가 여기 해당한다.
    """
    start = time.monotonic()
    ref = _driver.get_all_positions()   # 마지막으로 움직임이 확인된 위치
    ref_time = start

    while True:
        time.sleep(POLL)
        now = _driver.get_all_positions()
        stamp = time.monotonic()
        elapsed = stamp - start

        gaps = {s: abs(goal[s] - now[s]) for s in JOINT_IDS if now[s] is not None}
        if gaps and max(gaps.values()) <= ARRIVE_TICK:
            return elapsed, "도착"

        moved = max(
            (abs(now[s] - ref[s]) for s in JOINT_IDS if now[s] is not None and ref[s] is not None),
            default=0,
        )
        if moved > STILL_TICK:
            ref, ref_time = now, stamp
        elif elapsed >= START_GRACE and stamp - ref_time >= STILL_HOLD:
            left = " ".join(f"J{s} {g}틱" for s, g in sorted(gaps.items()) if g > ARRIVE_TICK)
            return elapsed, f"멈춤 {left}" if left else "멈춤"

        if elapsed >= ARRIVE_MAX:
            left = " ".join(f"J{s} {g}틱" for s, g in sorted(gaps.items()) if g > ARRIVE_TICK)
            print(f"[경고] {ARRIVE_MAX}초 내 완료 못 함 — {left}")
            return elapsed, "시간초과"


def run_steps(title, steps):
    if not _driver.is_connected() and not _driver.connect():
        raise ConnectionError(f"SO-ARM101 연결 실패: {PORT}")
    _driver.set_all_torque(True)

    print(f"\n=== {title} === (속도 배율 {SPEED_SCALE * 100:.0f}%)")
    last = sum(1 for s in steps if s[0] == "POS")
    speeds = {}
    index = 0
    prev = None

    for kind, *rest in steps:
        if kind == "SPD":
            speeds = rest[0]
            continue

        pose, name = rest
        index += 1
        scaled, scale = _scaled(speeds)
        for sid in JOINT_IDS:
            _driver.set_speed(sid, scaled[sid])
        if scale < SPEED_SCALE - 0.01:
            print(
                f"[배율] {index}번 스텝은 {SPEED_SCALE * 100:.0f}% 대신 {scale * 100:.0f}% 적용"
                f" — 최고 속도 관절이 상한 {SPEED_LIMIT}에 걸려 비율 유지를 위해 전체를 낮춤"
            )
        _driver.set_all_positions(pose)

        if _grip_only(pose, prev):
            time.sleep(GRIP_WAIT)
            took, why = GRIP_WAIT, "그리퍼 고정대기"
        else:
            took, why = _wait_arrival(pose)
        prev = pose

        joints = " | ".join(f"J{j}:{pose[j]}" for j in JOINT_IDS)
        print(f"[이동] {index} {name}  {joints}  ({took:.2f}초 · {why})")

        if index != last and WAIT > 0:
            print(f"[대기] {WAIT}초")
            time.sleep(WAIT)


